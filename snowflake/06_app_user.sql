-- Service user for the Streamlit app: it may only use the FORK agent and read the data behind it.
-- Run as ACCOUNTADMIN. The token secret is shown ONCE in the output of the last statement:
-- copy it straight into the app's secrets (SNOWFLAKE_PAT) and nowhere else.

USE ROLE ACCOUNTADMIN;

-- 1. Role with only what the app needs
CREATE ROLE IF NOT EXISTS FORK_APP_ROLE;
GRANT USAGE ON WAREHOUSE GENERAL_AGENT_WH TO ROLE FORK_APP_ROLE;
GRANT USAGE ON DATABASE GENERAL_AGENT_DEMO TO ROLE FORK_APP_ROLE;
GRANT USAGE ON SCHEMA GENERAL_AGENT_DEMO.RESTAURANT TO ROLE FORK_APP_ROLE;
GRANT SELECT ON TABLE GENERAL_AGENT_DEMO.RESTAURANT.VISITS TO ROLE FORK_APP_ROLE;
GRANT SELECT ON SEMANTIC VIEW GENERAL_AGENT_DEMO.RESTAURANT.FORK_VISITS_SEMANTIC TO ROLE FORK_APP_ROLE;
GRANT USAGE ON AGENT GENERAL_AGENT_DEMO.RESTAURANT.AGENTFORK TO ROLE FORK_APP_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE FORK_APP_ROLE;

-- 2. Service user (no password, cannot sign in to Snowsight)
CREATE USER IF NOT EXISTS FORK_APP_USER
  TYPE = SERVICE
  DEFAULT_ROLE = FORK_APP_ROLE
  DEFAULT_WAREHOUSE = GENERAL_AGENT_WH
  COMMENT = 'Streamlit app for the FORK demo agent';
GRANT ROLE FORK_APP_ROLE TO USER FORK_APP_USER;

-- 3. Streamlit Cloud has no fixed IP addresses, so the token cannot be tied to a network policy.
--    This lets the token work without one (any network policy that is set is still enforced).
CREATE AUTHENTICATION POLICY IF NOT EXISTS GENERAL_AGENT_DEMO.RESTAURANT.FORK_APP_PAT_POLICY
  PAT_POLICY = (NETWORK_POLICY_EVALUATION = ENFORCED_NOT_REQUIRED);
ALTER USER FORK_APP_USER SET AUTHENTICATION POLICY GENERAL_AGENT_DEMO.RESTAURANT.FORK_APP_PAT_POLICY;

-- 4. The token, limited to the app's role, valid for 90 days. Copy the token_secret from the output now.
ALTER USER FORK_APP_USER
  ADD PROGRAMMATIC ACCESS TOKEN FORK_APP_TOKEN
  ROLE_RESTRICTION = 'FORK_APP_ROLE'
  DAYS_TO_EXPIRY = 90
  COMMENT = 'Streamlit app for the FORK demo agent';
