"""Build the ready-to-run Snowflake SQL files from the source files in agent/.

Snowsight runs one pasted file, so the SQL files carry a copy of the YAML and the instructions.
Edit the source files, then run:  python agent/build_sql.py

  agent/fork_visits_semantic.yaml          -> snowflake/03_semantic_view.sql
  agent/orchestration_instructions.md  \\
  agent/response_instructions.md        +-> snowflake/04_agent.sql
  agent/sample_questions.txt           /
  agent/eval_set.json                      -> snowflake/05_eval_set.sql
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AGENT = ROOT / "agent"
SNOWFLAKE = ROOT / "snowflake"

SEMANTIC_VIEW = "GENERAL_AGENT_DEMO.RESTAURANT.FORK_VISITS_SEMANTIC"
AGENT_NAME = "GENERAL_AGENT_DEMO.RESTAURANT.FORK_AGENT"
WAREHOUSE = "GENERAL_AGENT_WH"
ROLE = "GENERAL_AGENT_ROLE"


def read(name):
    text = (AGENT / name).read_text().strip()
    assert "$$" not in text, f"{name} must not contain $$"
    return text


def indent(text, spaces):
    pad = " " * spaces
    return "\n".join(pad + line if line else "" for line in text.splitlines())


def build_semantic_view():
    sql = f"""-- Create the semantic view {SEMANTIC_VIEW}.
-- Generated by agent/build_sql.py from agent/fork_visits_semantic.yaml. Edit the YAML, not this file.
-- Run the whole worksheet as the role that owns the schema GENERAL_AGENT_DEMO.RESTAURANT.
-- The CALL validates the YAML and fails with an error message if something is wrong.

USE WAREHOUSE {WAREHOUSE};

CALL SYSTEM$CREATE_SEMANTIC_VIEW_FROM_YAML(
  'GENERAL_AGENT_DEMO.RESTAURANT',
  $$
{read("fork_visits_semantic.yaml")}
  $$
);

-- The agent's role needs to read the view
GRANT SELECT ON SEMANTIC VIEW {SEMANTIC_VIEW} TO ROLE {ROLE};

-- Quick test: revenue and labour cost % per restaurant through the view
SELECT * FROM SEMANTIC_VIEW(
  {SEMANTIC_VIEW}
  DIMENSIONS VISITS.RESTAURANT
  METRICS VISITS.REVENUE, VISITS.LABOUR_COST_PCT
)
ORDER BY REVENUE DESC;
"""
    (SNOWFLAKE / "03_semantic_view.sql").write_text(sql)


def build_agent():
    questions = [q.strip() for q in read("sample_questions.txt").splitlines() if q.strip()]
    sample = "\n".join(f"    - question: {json.dumps(q)}" for q in questions)
    profile = json.dumps({"display_name": "FORK Analytics", "color": "blue"})
    sql = f"""-- Create the agent {AGENT_NAME} with the semantic view as its tool.
-- Generated by agent/build_sql.py from the instruction files in agent/. Edit those, not this file.
-- Run the whole worksheet as the role that owns the schema GENERAL_AGENT_DEMO.RESTAURANT.

USE WAREHOUSE {WAREHOUSE};

CREATE OR REPLACE AGENT {AGENT_NAME}
  COMMENT = 'Analytics agent for the fictional restaurant group FORK (synthetic demo data)'
  PROFILE = '{profile}'
  FROM SPECIFICATION
  $$
models:
  orchestration: auto

orchestration:
  budget:
    seconds: 300
    tokens: 32000

instructions:
  orchestration: |
{indent(read("orchestration_instructions.md"), 4)}
  response: |
{indent(read("response_instructions.md"), 4)}
  sample_questions:
{sample}

tools:
  - tool_spec:
      type: "cortex_analyst_text_to_sql"
      name: "FORK_VISITS"
      description: "Bookings, guests, sales and costs for the seven FORK restaurants, one row per table or party, 2 January 2025 to 25 October 2026. Use for revenue, guests, spend per guest, booking channels, no-shows and cancellations, food cost %, beverage cost %, labour cost % and prime cost %, by restaurant, city, concept, service, date, weekday and month. Amounts in DKK ex VAT."
  - tool_spec:
      type: "data_to_chart"
      name: "data_to_chart"
      description: "Creates a chart from query results."

tool_resources:
  FORK_VISITS:
    semantic_view: "{SEMANTIC_VIEW}"
    execution_environment:
      type: "warehouse"
      warehouse: "{WAREHOUSE}"
      query_timeout: 60
  $$;

-- The app's role needs to use the agent
GRANT USAGE ON AGENT {AGENT_NAME} TO ROLE {ROLE};

DESCRIBE AGENT {AGENT_NAME};
"""
    (SNOWFLAKE / "04_agent.sql").write_text(sql)


def build_eval_set():
    items = json.loads(read("eval_set.json"))
    quote = lambda text: "'" + text.replace("'", "''") + "'"
    rows = ",\n".join(f"  ({quote(i['question'])}, {quote(i['expected'])})" for i in items)
    sql = f"""-- Evaluation set for {AGENT_NAME}: questions with the expected answer, checked against the data.
-- Generated by agent/build_sql.py from agent/eval_set.json. Edit the JSON, not this file.
-- Then pick the table GENERAL_AGENT_DEMO.RESTAURANT.FORK_AGENT_EVAL when you create the eval set in Snowsight
-- (query column INPUT_QUERY, ground truth column GROUND_TRUTH).

USE WAREHOUSE {WAREHOUSE};

CREATE OR REPLACE TABLE GENERAL_AGENT_DEMO.RESTAURANT.FORK_AGENT_EVAL (
  INPUT_QUERY  VARCHAR,
  GROUND_TRUTH VARIANT
);

INSERT INTO GENERAL_AGENT_DEMO.RESTAURANT.FORK_AGENT_EVAL (INPUT_QUERY, GROUND_TRUTH)
SELECT q, OBJECT_CONSTRUCT('ground_truth_output', a)
FROM VALUES
{rows}
AS t(q, a);

SELECT * FROM GENERAL_AGENT_DEMO.RESTAURANT.FORK_AGENT_EVAL;
"""
    (SNOWFLAKE / "05_eval_set.sql").write_text(sql)


if __name__ == "__main__":
    build_semantic_view()
    build_agent()
    build_eval_set()
    print("wrote snowflake/03_semantic_view.sql, 04_agent.sql and 05_eval_set.sql")
